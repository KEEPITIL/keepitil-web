#!/usr/bin/env python3
"""Branded invite pages for every KEEPITIL app (Joe, 2026-11-23).

"We do the same thing to all apps. 3 buttons. All invite links.
 Apple (Apple Store), Google (google play store), Web (website homepage).
 They are all branded links only. Icon image with simple text."

One static page per app: the app icon, the app name, "You're invited to join for free.", and three
buttons in order Apple / Google / Web. A store button is a link only while that store listing is
live; otherwise it is a disabled "Coming soon" (no app has a Google Play listing yet). No scripts,
no redirects, no external requests. TUITEA's page (app/tuitea/invite/) is hand-made and not
generated here. Re-run after editing APPS:  python3 tools/build-invite-pages.py
"""
import html, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TUITEA = open(os.path.join(ROOT, 'app/tuitea/invite/index.html')).read()
GLYPH = {k: re.search(r'<svg class="glyph %s"[\s\S]*?</svg>' % c, TUITEA).group(0)
         for k, c in (('apple', 'glyph-apple'), ('android', 'glyph-android'), ('web', 'line glyph-web'))}

APPS = [
    # slug, page dir, name, icon (site path), App Store id or None, web home, background, accent
    dict(dir='games/kmob/invite', name='KMOB', full='KMOB: Endless War', icon='/games/kmob/icon-512.png',
         apple='6822852714', web='/games/kmob/', bg='#0E1A33', accent='#F2B544'),
    dict(dir='app/wifi-remote/invite', name='WiFi Remote', full='WiFi Remote for Smart TVs',
         icon='/app/wifi-remote/invite/icon-256.png', apple='6790006312', web='/', bg='#101827', accent='#5EC8FF'),
    dict(dir='invite', name='KEEPITIL', full='KEEPITIL', icon='/icon-512.png',
         apple=None, web='/', bg='#0B0B0F', accent='#00E5FF'),
    dict(dir='app/findmyweed/invite', name='Find My Weed', full='Find My Weed',
         icon='/app/findmyweed/icons/icon.svg', apple=None, web='/app/findmyweed/', bg='#0F1A12', accent='#7BD88F'),
    dict(dir='app/kaitarako/invite', name='Kai Tarako', full='Kai Tarako',
         icon='/app/kaitarako/icon-512.png', apple=None, web='/app/kaitarako/', bg='#2B2118', accent='#FFC857'),
]

