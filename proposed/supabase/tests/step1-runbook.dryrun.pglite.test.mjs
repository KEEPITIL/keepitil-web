async function as(pg, role, uid, sql, params) {
  return pg.transaction(async (tx) => { await tx.exec('set local role ' + role); await tx.query("select set_config('request.jwt.claim.sub', $1, true)", [uid || '']); return (await tx.query(sql, params)).rows; });
}
// ACLs compared as SETS (sorted items): a rollback re-grants the same privileges, possibly listed in another order
async function snapshot(pg) {
  const q = async (s) => (await pg.query(s)).rows;
  return {
    fns: await q("select p.oid::regprocedure::text f, md5(pg_get_functiondef(p.oid)) m, coalesce((select string_agg(x::text, ',' order by x::text) from unnest(p.proacl) x), '') a from pg_proc p where p.pronamespace = 'public'::regnamespace order by 1"),
    trg: await q("select tgrelid::regclass::text t, tgname, tgenabled from pg_trigger where not tgisinternal order by 1, 2"),
    pol: await q("select tablename, policyname, cmd, qual, with_check from pg_policies where schemaname = 'public' order by 1, 2"),
    rel: await q("select relname, relrowsecurity, coalesce((select string_agg(x::text, ',' order by x::text) from unnest(relacl) x), '') a from pg_class where relnamespace = 'public'::regnamespace order by 1"),
    col: await q("select attrelid::regclass::text t, attname, coalesce((select string_agg(x::text, ',' order by x::text) from unnest(attacl) x), '') a from pg_attribute where attrelid in ('public.app_users'::regclass, 'public.event_orders'::regclass) and attnum > 0 order by 1, 2"),
  };
}
const checks = async (pg) => (await pg.query(F.checks)).rows;

test('vendored #67 files are byte-exact (MANIFEST sha256)', () => {
  const m = JSON.parse(rd(VEN, 'MANIFEST.json'));
  for (const f of m.files) assert.equal(createHash('sha256').update(readFileSync(join(VEN, f.vendored))).digest('hex'), f.sha256, f.vendored);
});

test('runbook pin table = the md5 of every SQL file it runs (raw bytes); a 1-byte edit is caught', () => {
  const rb = rd(P, 'RUNBOOK-step1.md');
  const pins = [...rb.matchAll(/^\s*\| `([\w.-]+\.sql)` \| `([0-9a-f]{32})` \|$/gm)].map((m) => [m[1], m[2]]);
  const where = {
    'backup-functions.sql': [P, 'runbook'], 'postapply-checks.sql': [P, 'runbook'],
    'event_orders_guard.PROPOSED.sql': [VEN], 'event_orders_guard.ROLLBACK.sql': [VEN],
    'payouts_flag_lock.PROPOSED.sql': [P, 'supabase', 'sql'], 'payouts_flag_lock.ROLLBACK.sql': [P, 'supabase', 'sql'],
  };
  assert.deepEqual(pins.map(([f]) => f).sort(), Object.keys(where).sort(), 'the pin table lists exactly the six SQL files');
  const md5 = (b) => createHash('md5').update(b).digest('hex');
  for (const [f, want] of pins) {
    const raw = readFileSync(join(...where[f], f));
    assert.equal(md5(raw), want, f);
    const edited = Buffer.concat([raw, Buffer.from(' ')]);          // negative control
    assert.notEqual(md5(edited), want, `${f}: an edited copy must fail the pin`);
  }
  assert.ok(!rb.includes('-f .github/internal'), 'no step runs a SQL file from another repo path');
  assert.ok(!/psql[^\n]*-f proposed\//.test(rb), 'every psql -f runs the pinned staging copy ($S)');
});

test('DRY RUN: backup → #67 → #182 → post-apply checks all ok → rollback #182 → rollback #67 → identical to live', async () => {
  const pg = await live();
  const before = await snapshot(pg);
  // (1) backup of the function definitions: the three md5s match the PRECHECK baselines
  const bk = (await pg.query(F.backup)).rows;
  assert.deepEqual(bk.map((r) => [r.function, r.md5]), [
    ['check_in_ticket(text)', 'bc0a07ce552ea84acd4c0130a5cf8df3'], ['event_checkin_scan(text)', 'd6f2977aa8a0f8eebaadfac021892cbb'],
    ['mark_payouts_enabled()', '975786ee803b22f894ef01af63f20d5c']]);
  assert.ok(bk.every((r) => /^CREATE OR REPLACE FUNCTION/.test(r.definition)));
  // the checks read f before the apply (the live holes) — proof they can fail
  const pre = await checks(pg);
  assert.deepEqual(pre.filter((r) => !r.ok).map((r) => r.check_name).length, 6, JSON.stringify(pre));   // 1, 2, 4, 6, 7, 8
  // (2)(3) the runbook order: #67, then (connect-status + page: not database steps), then #182
  await pg.exec(F.g67);
  await pg.exec(F.l182);
  // (4) post-apply checks: all ok
  const post = await checks(pg);
  assert.deepEqual(post.map((r) => r.ok), Array(8).fill(true), JSON.stringify(post.filter((r) => !r.ok)));
  // and behaviour, as the checks claim: an organizer cannot rewrite an order; a host cannot self-mark; the door works
  await assert.rejects(as(pg, 'authenticated', ORG, "update public.event_orders set status = 'refunded' where qr_token = 'qr_door'"), (e) => e.code === '42501');
  await assert.rejects(as(pg, 'authenticated', HOST, 'select public.mark_payouts_enabled()'), /permission denied/);
  await assert.rejects(as(pg, 'authenticated', HOST, 'update public.app_users set payouts_enabled = true'), /only be set by the server/);
  assert.equal((await as(pg, 'service_role', null, "select public.set_payouts_from_stripe('acct_1Host', true, true, null) n"))[0].n, 1);
  assert.equal((await as(pg, 'authenticated', ORG, "select public.event_checkin_scan('qr_door') r"))[0].r.result, 'admitted');
  // (5) rollback, reverse order: #182 first, then #67
  await pg.exec(F.l182rb);
  await pg.exec(F.g67rb);
  const after = await snapshot(pg);
  assert.deepEqual(after, before, 'functions (md5 + ACL), triggers, policies, table and column ACLs: identical to live');
  assert.deepEqual((await checks(pg)).filter((r) => !r.ok).length, 6, 'the holes are back after a rollback, as the rollback notes warn');
});

test('STOP RULE: a failed PRECHECK aborts with nothing changed (each file is one transaction)', async () => {
  // someone changed a live function since the baseline: #182's PRECHECK must refuse and leave everything as it was
  const pg = await live();
  await pg.exec(F.g67);
  await pg.exec("create or replace function public.mark_payouts_enabled() returns void language sql security definer set search_path to 'public' as $$ select null::void $$");
  const mid = await snapshot(pg);
  await assert.rejects(pg.exec(F.l182), /PRECHECK: public.mark_payouts_enabled\(\) differs from the 2026-11-17 baseline/);
  await pg.exec('rollback');
  assert.deepEqual(await snapshot(pg), mid, 'nothing from #182 was applied');
  // runbook: then roll back what was applied in this window (#67) and report
  await pg.exec(F.g67rb);
  assert.equal((await pg.query("select count(*)::int n from pg_trigger where tgname = 'event_orders_guard_columns'")).rows[0].n, 0);
  // #67 refuses a second apply (guard already exists) without changing anything
  const pg2 = await live(); await pg2.exec(F.g67); const s = await snapshot(pg2);
  await assert.rejects(pg2.exec(F.g67), /PRECHECK: event_orders_guard_columns already exists/);
  await pg2.exec('rollback');
  assert.deepEqual(await snapshot(pg2), s);
});

test('#182 alone (if #67 must wait) and the checks still tell the two apart', async () => {
  const pg = await live();
  await pg.exec(F.l182);
  const r = await checks(pg);
  assert.deepEqual(r.map((x) => x.ok), [false, false, true, true, true, true, true, true], JSON.stringify(r));
});
