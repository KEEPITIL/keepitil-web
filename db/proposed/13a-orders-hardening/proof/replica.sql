-- Roles anon / authenticated / service_role / postgres / authenticator are created by the harness (NOSUPERUSER stand-ins, service_role has BYPASSRLS like Supabase).
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema auth to anon, authenticated, service_role;
create table auth.users (id uuid primary key, email text);

create table public.app_users (id uuid primary key, handle text, email text, display_name text);
create table public.events (id bigint generated by default as identity primary key, slug text unique, title text, owner_handle text, status text default 'published', starts_at timestamptz, cover_url text, venue text, city text, genres text);
create table public.ticket_tiers (id bigint generated by default as identity primary key, event_id bigint references public.events(id) on delete cascade, name text, price_cents int, qty_total int, qty_sold int not null default 0);
create function public.my_handle() returns text language sql stable security definer set search_path = public as $$ select handle from public.app_users where id = auth.uid() $$;
create function public.my_email() returns text language sql stable security definer set search_path = public as $$ select nullif(current_setting('request.jwt.claim.email', true), '') $$;

create table public.event_orders (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  tier_id bigint references public.ticket_tiers(id) on delete set null,
  buyer_email text,
  buyer_handle text,
  qty integer not null default 1,
  referral_code text,
  qr_token text default md5(random()::text || clock_timestamp()::text),
  status text not null default 'pending',
  amount_cents integer,
  created_at timestamptz not null default now(),
  stripe_session_id text,
  stripe_payment_intent text,
  application_fee_cents integer,
  organizer_acct text,
  checked_in_at timestamptz,
  constraint event_orders_status_check check (status in ('pending','paid','checked_in','refunded','cancelled'))
);
create index orders_event_idx on public.event_orders (event_id, status);
create unique index event_orders_session_tier_uidx on public.event_orders (stripe_session_id, tier_id) where stripe_session_id is not null;
create index event_orders_qr_token_idx on public.event_orders (qr_token);
alter table public.event_orders enable row level security;
-- captured table ACL: ALL (incl. TRUNCATE/MAINTAIN on PG17) for anon, authenticated, service_role
grant all on public.event_orders to anon, authenticated, service_role;
create policy event_orders_organizer_read on public.event_orders for select to authenticated
  using (event_id in (select events.id from public.events where events.owner_handle = public.my_handle()));
create policy event_orders_organizer_update on public.event_orders for update to authenticated
  using (event_id in (select events.id from public.events where events.owner_handle = public.my_handle()))
  with check (event_id in (select events.id from public.events where events.owner_handle = public.my_handle()));
create policy event_orders_owner_read on public.event_orders for select to authenticated using (buyer_email = public.my_email());
create policy orders_anon_insert on public.event_orders for insert to anon, authenticated with check (true);
grant select on public.events, public.ticket_tiers to anon, authenticated, service_role;
grant select on public.app_users to authenticated, service_role;
grant select on auth.users to service_role;

