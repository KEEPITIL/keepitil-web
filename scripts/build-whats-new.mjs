#!/usr/bin/env node
// Static "What's new" pages for KMOB and KBeats (Scout's spec, 2026-11-11). No dependencies.
//   node scripts/build-whats-new.mjs          writes games/<game>/whats-new/index.html from changelog.json
//   node scripts/build-whats-new.mjs --check  exits 1 if a committed page is stale
// The output is committed, so the page needs no JavaScript. Every string is HTML-escaped; the JSON holds no HTML.
// No forms, inputs, scripts, cookies, storage, analytics, embeds or external fonts. Coming-soon games get no page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const GAMES = {
  kmob: { name: 'KMOB', full: 'KMOB · Endless War', logo: '/games/kmob/icon-192.png', og: '/games/kmob/icon-512.png' },
  kbeats: { name: 'KBeats', full: 'KBeats', logo: '/games/kbeats/icon.svg', og: '/games/kbeats/icon.svg' },
};
const esc = s => String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const human = d => { const [y, m, day] = d.split('-').map(Number); return `${MONTHS[m - 1]} ${day}, ${y}`; };

export function validate(entries, game) {
  if (!Array.isArray(entries)) throw new Error(`${game}: changelog.json must be an array`);
  let prev = '9999-99-99';
  for (const e of entries) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.date || '')) throw new Error(`${game}: bad date ${e.date}`);
    if (e.date > prev) throw new Error(`${game}: entries must be newest first (${e.date})`);
    prev = e.date;
    if (typeof e.title !== 'string' || !e.title.trim()) throw new Error(`${game}: entry ${e.date} needs a title`);
    if (!Array.isArray(e.items) || !e.items.length || e.items.some(i => typeof i !== 'string' || !i.trim())) throw new Error(`${game}: entry ${e.date} needs items`);
    const extra = Object.keys(e).filter(k => !['date', 'title', 'items'].includes(k));
    if (extra.length) throw new Error(`${game}: entry ${e.date} has fields the public page must not carry: ${extra}`);
  }
  return entries;
}

export function render(game, entries) {
  const g = GAMES[game], url = `https://keepitil.com/games/${game}/whats-new/`;
  const desc = `The latest updates to ${g.name}, KEEPITIL's free ${game === 'kmob' ? 'army strategy game' : 'rhythm game'}, in plain words.`;
  const list = entries.length ? entries.map(e => `    <article class="wn-entry">
      <h2><time datetime="${esc(e.date)}">${esc(human(e.date))}</time> <span>${esc(e.title)}</span></h2>
      <ul>
${e.items.map(i => `        <li>${esc(i)}</li>`).join('\n')}
      </ul>
    </article>`).join('\n') : `    <p class="wn-empty">No new updates yet. Check back soon.</p>`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<!-- GENERATED by scripts/build-whats-new.mjs from changelog.json. Edit the JSON, then run the script. -->
<title>What's new in ${esc(g.name)} | KEEPITIL</title>
<meta name="description" content="${esc(desc)}">
<meta name="robots" content="index,follow">
<link rel="canonical" href="${url}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="KEEPITIL">
<meta property="og:title" content="What's new in ${esc(g.name)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${url}">
<meta property="og:image" content="https://keepitil.com${g.og}">
<link rel="icon" href="${g.logo}">
<link rel="stylesheet" href="/assets/css/tokens.css">
<style>
:root{color-scheme:dark}
*{box-sizing:border-box}
body{margin:0;background:#0a0a0f;color:#eef0f6;font:16px/1.6 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
.wn{max-width:44rem;margin:0 auto;padding:24px 16px 48px}
.wn-head{display:flex;align-items:center;gap:14px;margin-bottom:8px}
.wn-head img{width:56px;height:56px;border-radius:12px;flex:none}
.wn-game{margin:0;font-size:14px;font-weight:800;letter-spacing:.08em;color:#c9cde0;text-transform:uppercase}
h1{margin:0;font-size:28px;line-height:1.2}
.wn-play{display:inline-block;margin:14px 0 24px;padding:10px 18px;border-radius:999px;background:#fff;color:#0a0a0f;font-weight:800;text-decoration:none}
.wn-play:focus-visible,a:focus-visible{outline:3px solid #8ab4ff;outline-offset:2px}
.wn-entry{border-top:1px solid rgba(255,255,255,.14);padding:18px 0}
.wn-entry h2{margin:0 0 8px;font-size:18px;line-height:1.35}
.wn-entry time{display:block;font-size:14px;font-weight:600;color:#c9cde0}
.wn-entry ul{margin:0;padding-left:20px}
.wn-entry li{margin:6px 0}
.wn-empty{color:#c9cde0}
.wn-foot{margin-top:28px;font-size:14px;color:#c9cde0}
.wn-foot a{color:#fff}
</style>
</head>
<body>
<main class="wn">
  <header class="wn-head">
    <img src="${g.logo}" alt="" width="56" height="56">
    <div><p class="wn-game">${esc(g.full)}</p><h1>What's new</h1></div>
  </header>
  <a class="wn-play" href="/games/${game}/">Play ${esc(g.name)} now</a>
  <section aria-label="Updates">
${list}
  </section>
  <p class="wn-foot"><a href="/games/">All KEEPITIL Games</a></p>
</main>
</body>
</html>
`;
}

export function build({ check = false } = {}) {
  const stale = [];
  for (const game of Object.keys(GAMES)) {
    const dir = path.join(ROOT, 'games', game, 'whats-new');
    const entries = validate(JSON.parse(fs.readFileSync(path.join(dir, 'changelog.json'), 'utf8')), game);
    const html = render(game, entries), out = path.join(dir, 'index.html');
    if (check) { if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== html) stale.push(path.relative(ROOT, out)); }
    else fs.writeFileSync(out, html);
  }
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check'), stale = build({ check });
  if (stale.length) { console.error('stale What\'s new pages (run node scripts/build-whats-new.mjs): ' + stale.join(', ')); process.exit(1); }
  console.log(check ? 'whats-new: up to date' : 'whats-new: built');
}
