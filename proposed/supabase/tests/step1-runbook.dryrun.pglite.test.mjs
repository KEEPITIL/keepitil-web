const P = join(dirname(fileURLToPath(import.meta.url)), '..', '..');   // proposed/
const VEN = join(P, 'runbook', 'vendor');
const lf = (s) => s.replace(/\r\n/g, '\n');
const rd = (...p) => lf(readFileSync(join(...p), 'utf8'));
const F = {
  backup: rd(P, 'runbook', 'backup-functions.sql'), checks: rd(P, 'runbook', 'postapply-checks.sql'),
  g67: rd(VEN, 'event_orders_guard.PROPOSED.sql'), g67rb: rd(VEN, 'event_orders_guard.ROLLBACK.sql'),
  l182: rd(P, 'supabase', 'sql', 'payouts_flag_lock.PROPOSED.sql'), l182rb: rd(P, 'supabase', 'sql', 'payouts_flag_lock.ROLLBACK.sql'),
};
const OJ = JSON.parse(rd(VEN, 'event_orders.live.json'));
const ORG = '00000000-0000-4000-8000-0000000000aa', HOST = '00000000-0000-4000-8000-0000000000bb';

const ordersTable = () => {
  const cols = OJ.columns.map((c) => c.name === 'id' ? 'id bigint generated by default as identity primary key'
    : `${c.name} ${c.type}${c.null === 'NO' ? ' not null' : ''}${c.default != null ? ' default ' + c.default : ''}`);
  const checks = OJ.constraints.filter((k) => k.type === 'c').map((k) => `constraint ${k.name} ${k.def}`);
  const pol = OJ.policies.map((p) => `create policy ${p.name} on public.event_orders for ${p.cmd.toLowerCase()} to ${p.roles.join(', ')}` +
    (p.using ? ` using (${p.using})` : '') + (p.check ? ` with check (${p.check})` : '') + ';').join('\n');
  return `create table public.event_orders (${cols.concat(checks).join(', ')}, foreign key (event_id) references public.events(id));
    ${OJ.indexes.filter((i) => !/_pkey /.test(i)).map((i) => i + ';').join('\n')}
    alter table public.event_orders enable row level security; ${pol}
    grant select, update, delete on public.event_orders to anon, authenticated; grant all on public.event_orders to service_role;`;
};
