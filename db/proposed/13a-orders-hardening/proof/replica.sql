create function public.has_event_ticket(p_slug text) returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.event_orders o join public.events e on e.id = o.event_id where e.slug = p_slug and o.buyer_email = public.my_email() and o.status = 'paid') $$;
revoke all on function public.has_event_ticket(text) from public; grant execute on function public.has_event_ticket(text) to anon, authenticated, service_role;
create function public.organizer_dashboard() returns table(slug text, sold bigint, gross bigint, checked_in bigint) language sql stable security definer set search_path = public as $$
  select e.slug, coalesce(sum(o.qty) filter (where o.status = 'paid'), 0)::bigint, coalesce(sum(o.amount_cents) filter (where o.status = 'paid'), 0)::bigint, count(*) filter (where o.checked_in_at is not null)
  from public.events e left join public.event_orders o on o.event_id = e.id where e.owner_handle = public.my_handle() group by e.slug order by e.slug $$;
revoke all on function public.organizer_dashboard() from public; grant execute on function public.organizer_dashboard() to authenticated, service_role;

