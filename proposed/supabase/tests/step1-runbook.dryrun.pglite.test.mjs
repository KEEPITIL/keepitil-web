// DRY RUN of proposed/RUNBOOK-step1.md (STEP 1: #67 event_orders guard + #182 payout-flag lock) in a real in-memory
// Postgres (PGlite) built from the read-only live baselines. Runs the runbook's own files, verbatim and in its order:
//   backup-functions.sql → #67 SQL → (connect-status deploy + page ship: not database steps) → #182 SQL →
//   postapply-checks.sql → rollback #182 → rollback #67 → the catalog is IDENTICAL to before.
// Plus the stop rule: a failed PRECHECK aborts with nothing changed. Nothing touches keepitil-prod.
//   node --test proposed/supabase/tests/step1-runbook.dryrun.pglite.test.mjs
