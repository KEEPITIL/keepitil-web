/* build-variants.mjs - R1 fix generator (proposal only; nothing here touches any database).
   Writes the R1 variants of the APPLY/ROLLBACK packs under packs/ from the committed originals, mechanically, so that a reviewer can diff
   original -> variant and see exactly three kinds of change and nothing else:
     (1) LOCK     every APPLY/ROLLBACK pack gets `SELECT pg_advisory_xact_lock(<KEY>);` as the FIRST statement after its first BEGIN;
     (2) ACL-SORT F3 FORWARD / ROLLBACK / DRIFT_QUERY / POSTCHECKS hash (and show) ACLs through an entry-order-independent expression instead of relacl::text etc.;
     (3) MAINTAIN F3 FORWARD revokes MAINTAIN (PostgreSQL 17+) on event_media / venue_media from PUBLIC, anon, authenticated, remembering which grants existed; F3 ROLLBACK restores exactly those.
   Usage:  node build-variants.mjs            write packs/ (idempotent)
           node build-variants.mjs --check    exit 1 if the committed packs/ differ from what the originals generate
           node build-variants.mjs --lock <in.sql> [--out <out.sql>]   locked wrapper for ANY other pack file (e.g. the real PR #91/#92 file); prints to stdout without --out */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";

const HERE = dirname(fileURLToPath(import.meta.url)), PROPOSED = join(HERE, "..");
const OUT = join(HERE, "packs");
/* The one advisory-lock key used by EVERY pack, so any two runs (APPLY vs APPLY, APPLY vs ROLLBACK, any pack vs any pack) queue behind each other.
   Derivation (reproducible): first 8 bytes (big-endian, signed) of sha256("keepitil-web db/proposed pack-run-serializer v1"). Single-bigint-key space, distinct from the two-int4 form. */
export const KEY_SEED = "keepitil-web db/proposed pack-run-serializer v1";
export const LOCK_KEY = createHash("sha256").update(KEY_SEED).digest().readBigInt64BE(0).toString();
export const LOCK_SQL = `-- R1-LOCK: serialise pack runs. pg_advisory_xact_lock(${LOCK_KEY}) = signed int64 of the first 8 bytes of sha256("${KEY_SEED}"); the SAME key is used by every APPLY/ROLLBACK pack,
-- so a second run (any pack) WAITS here until the first transaction commits or rolls back (transaction-scoped: released automatically). Waiting is unbounded unless the session sets lock_timeout.
SELECT pg_advisory_xact_lock(${LOCK_KEY});`;

const rd = (...p) => readFileSync(join(...p), "utf8");
const once = (s, from, to, what) => { const i = s.indexOf(from); if (i < 0) throw new Error("anchor not found: " + what); if (s.indexOf(from, i + 1) >= 0) throw new Error("anchor not unique: " + what); return s.slice(0, i) + to + s.slice(i + from.length); };
const all = (s, from, to, n, what) => { const c = s.split(from).length - 1; if (c !== n) throw new Error(`${what}: expected ${n} occurrence(s), found ${c}`); return s.split(from).join(to); };

/* ---------------------------------------------------------------- (1) LOCK */
export function lockPack(sql, what = "pack") {
  if (sql.includes("pg_advisory_xact_lock(" + LOCK_KEY + ")")) return sql;           // idempotent
  const m = /^(begin|start transaction);[ \t]*\r?$/im.exec(sql);
  if (!m) throw new Error(what + ": no top-level BEGIN; line found");
  if (/\/\*/.test(sql.slice(0, m.index)) && !/\*\//.test(sql.slice(0, m.index))) throw new Error(what + ": BEGIN; is inside a block comment");
  const end = m.index + m[0].length;
  return sql.slice(0, end) + "\n" + LOCK_SQL + sql.slice(end);
}

/* ---------------------------------------------------------------- (2) ACL-SORT */
/* NULL stays NULL (default ACL); otherwise '{e1,e2,...}' with the aclitem entries sorted by their text under the C collation, so the result does not depend on entry order or database collation. */
export const aclSorted = (x) => `CASE WHEN ${x} IS NULL THEN NULL ELSE (SELECT '{'||coalesce(string_agg(acl_e::text,',' ORDER BY acl_e::text COLLATE "C"),'')||'}' FROM unnest(${x}) acl_e) END`;
export function sortAcls(sql, copies, what) {
  let o = sql;
  o = all(o, "c.relacl::text acl", aclSorted("c.relacl") + " acl", 2 * copies, what + " relacl");
  o = all(o, "a.attacl::text acl", aclSorted("a.attacl") + " acl", 2 * copies, what + " attacl");
  o = all(o, "p.proacl::text acl", aclSorted("p.proacl") + " acl", 2 * copies, what + " proacl");
  o = all(o, "'acl',nspacl::text", "'acl'," + aclSorted("nspacl"), copies, what + " nspacl");
  if (/(relacl|attacl|proacl|nspacl)::text/.test(o)) throw new Error(what + ": an order-sensitive ACL text cast is left");
  return o;
}

const HEADER = (src, notes) => `-- R1-FIX VARIANT (draft/r1-fix-f3-acl-locks; PROPOSAL ONLY, NOT APPLIED). GENERATED by db/proposed/r1-fix-f3-acl-locks/build-variants.mjs from ${src}.
-- Differences from the original, and nothing else: ${notes}
-- Do not edit by hand: re-run the generator (node build-variants.mjs --check fails if this file drifts from its original).
`;

/* ---------------------------------------------------------------- (3) MAINTAIN */
const MAINTAIN_FWD = `
-- R1 (PostgreSQL 17+ only): MAINTAIN is part of ALL and is NOT covered by the S1 revokes above, so anon/authenticated could still take
-- ACCESS EXCLUSIVE locks (LOCK TABLE) on the media tables and block every reader (reproduced on real PG 17.6, 11B CC.8).
-- The pre-state is recorded (direct ACL entries only) so the rollback restores EXACTLY what existed. No-op on servers older than 17 (the table stays empty).
CREATE TABLE atlas_media_guard.maintain_prior_grants (
 table_name text NOT NULL,
 grantee text NOT NULL,
 PRIMARY KEY (table_name, grantee)
);
REVOKE ALL ON TABLE atlas_media_guard.maintain_prior_grants FROM PUBLIC,anon,authenticated,service_role;
DO $maintain$
BEGIN
 IF current_setting('server_version_num')::int >= 170000 THEN
 INSERT INTO atlas_media_guard.maintain_prior_grants(table_name,grantee)
 SELECT c.relname::text, CASE WHEN a.grantee=0 THEN 'PUBLIC' ELSE pg_get_userbyid(a.grantee) END
 FROM pg_class c, LATERAL aclexplode(c.relacl) a
 WHERE c.oid IN ('public.event_media'::regclass,'public.venue_media'::regclass)
 AND a.privilege_type='MAINTAIN'
 AND (a.grantee=0 OR a.grantee IN ('anon'::regrole,'authenticated'::regrole));
 EXECUTE 'REVOKE MAINTAIN ON TABLE public.event_media,public.venue_media FROM PUBLIC,anon,authenticated';
 END IF;
END;
$maintain$;
`;
const MAINTAIN_RB = `-- R1 (PostgreSQL 17+ only): restore exactly the MAINTAIN grants the forward recorded and removed (none if none existed; skipped if the table is absent).
DO $maintain_restore$
DECLARE r record;
BEGIN
 IF current_setting('server_version_num')::int >= 170000
 AND to_regclass('atlas_media_guard.maintain_prior_grants') IS NOT NULL THEN
 FOR r IN SELECT table_name,grantee FROM atlas_media_guard.maintain_prior_grants ORDER BY table_name,grantee LOOP
 EXECUTE format('GRANT MAINTAIN ON TABLE public.%I TO %s', r.table_name,
 CASE WHEN r.grantee='PUBLIC' THEN 'PUBLIC' ELSE quote_ident(r.grantee) END);
 END LOOP;
 END IF;
END;
$maintain_restore$;
`;
const PC_MAINTAIN = ` has_table_privilege('authenticated',c.oid,'DELETE') AS authenticated_delete,
 CASE WHEN current_setting('server_version_num')::int >= 170000 THEN has_table_privilege('anon',c.oid,'MAINTAIN') END AS anon_maintain,
 CASE WHEN current_setting('server_version_num')::int >= 170000 THEN has_table_privilege('authenticated',c.oid,'MAINTAIN') END AS authenticated_maintain,
 coalesce((SELECT bool_or(x.grantee=0 AND x.privilege_type='MAINTAIN') FROM aclexplode(c.relacl) x),false) AS public_maintain`;

const FP = "2026-11-09_f3_media_rls_connect_publish_gate_";
const F3 = (k) => FP + k + "_PROPOSED.sql";

export function buildAll() {
  const files = new Map();                                   // relative path under packs/ -> content
  const f3d = join(PROPOSED, "f3-publish-gate");
  /* F3 */
  { let s = rd(f3d, F3("FORWARD"));
    s = sortAcls(s, 2, "F3 FORWARD"); s = lockPack(s, "F3 FORWARD");
    s = once(s, "REVOKE DELETE ON TABLE public.event_media,public.venue_media FROM authenticated;\n", "REVOKE DELETE ON TABLE public.event_media,public.venue_media FROM authenticated;\n" + MAINTAIN_FWD, "F3 FORWARD maintain anchor");
    files.set("f3/" + F3("FORWARD"), HEADER("f3-publish-gate/" + F3("FORWARD"), "(1) advisory lock first in the transaction; (2) the drift check and the saved rollback guard hash ACLs order-independently; (3) REVOKE MAINTAIN on event_media/venue_media (PG17+, version-guarded) with a recorded pre-state (atlas_media_guard.maintain_prior_grants). The stale baseline literal is unchanged and MUST be re-captured with the R1 DRIFT_QUERY (its hash differs from the order-sensitive one by construction).") + s); }
  { let s = rd(f3d, F3("ROLLBACK"));
    s = sortAcls(s, 2, "F3 ROLLBACK"); s = lockPack(s, "F3 ROLLBACK");
    s = once(s, "GRANT TRUNCATE ON TABLE public.event_media,public.venue_media,public.profile_meta TO anon,authenticated;\n", "GRANT TRUNCATE ON TABLE public.event_media,public.venue_media,public.profile_meta TO anon,authenticated;\n" + MAINTAIN_RB, "F3 ROLLBACK maintain anchor");
    s = once(s, "DROP TABLE atlas_media_guard.rollback_guard;\n", "DROP TABLE IF EXISTS atlas_media_guard.maintain_prior_grants;\nDROP TABLE atlas_media_guard.rollback_guard;\n", "F3 ROLLBACK drop anchor");
    files.set("f3/" + F3("ROLLBACK"), HEADER("f3-publish-gate/" + F3("ROLLBACK"), "(1) advisory lock first in the transaction; (2) the pre-check and the final exactness guard hash ACLs order-independently; (3) restores exactly the MAINTAIN grants the R1 forward recorded, then drops its record table.") + s); }
  { let s = rd(f3d, F3("DRIFT_QUERY")); s = sortAcls(s, 1, "F3 DRIFT_QUERY");
    files.set("f3/" + F3("DRIFT_QUERY"), HEADER("f3-publish-gate/" + F3("DRIFT_QUERY"), "(2) ACLs are hashed order-independently (relacl/attacl/proacl/nspacl through a sorted aclitem list). Run it with SET search_path = public, extensions exactly as before.") + s); }
  { let s = rd(f3d, F3("POSTCHECKS"));
    s = once(s, " has_table_privilege('authenticated',c.oid,'DELETE') AS authenticated_delete", PC_MAINTAIN, "F3 POSTCHECKS maintain anchor");
    s = once(s, "SELECT c.relname,c.relacl::text AS acl,", "SELECT c.relname," + aclSorted("c.relacl") + " AS acl,", "F3 POSTCHECKS acl anchor");
    files.set("f3/" + F3("POSTCHECKS"), HEADER("f3-publish-gate/" + F3("POSTCHECKS"), "(2) the displayed ACL is sorted; (3) three extra columns in the SAME statement (anon_maintain, authenticated_maintain on PG17+, public_maintain from the ACL): all must be false/NULL after the R1 forward. Still 8 statements.") + s); }
  /* the other packs: lock only */
  const locked = [
    ["pr91", join(PROPOSED, "10a-privacy-dependency/upstream"), ["APPLY-1.sql", "APPLY-1B-kind-check.sql", "APPLY-2.sql", "ROLLBACK-2.sql"]],
    ["pr92", join(PROPOSED, "10a-privacy-dependency/upstream"), ["APPLY-92.sql"]],
    ["10a", join(PROPOSED, "10a-privacy-dependency"), ["APPLY-1C-grant-narrowing_PROPOSED.sql", "APPLY-92-44col_PROPOSED.sql", "ROLLBACK-1C_PROPOSED.sql", "ROLLBACK-2-after-1C_PROPOSED.sql"]],
    ["11a", join(PROPOSED, "11a-upload-ownership"), ["can_upload_event_media_PROPOSED.sql", "ROLLBACK_PROPOSED.sql"]],
    ["pr91", join(PROPOSED, "11b-combined-rehearsal/rollbacks"), ["ROLLBACK-1.sql", "ROLLBACK-1B-kind-check.sql"]],
    ["pr92", join(PROPOSED, "11b-combined-rehearsal/rollbacks"), ["ROLLBACK-92.sql"]],
  ];
  for (const [grp, dir, names] of locked) for (const n of names) {
    const src = rd(dir, n); const rel = dir.slice(PROPOSED.length + 1) + "/" + n;
    files.set(`locked/${grp}/${n}`, HEADER(rel, "(1) advisory lock first in the transaction (byte-identical otherwise: the original text follows this header, with the lock inserted after its first BEGIN;).") + lockPack(src, rel)); }
  return files;
}

/* ---------------------------------------------------------------- CLI */
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const a = process.argv.slice(2);
  if (a[0] === "--lock") { const out = lockPack(rd(".", a[1]), a[1]); const o = a.indexOf("--out"); if (o >= 0) writeFileSync(a[o + 1], out); else process.stdout.write(out); }
  else {
    const files = buildAll(); let bad = 0;
    for (const [rel, content] of files) { const p = join(OUT, rel);
      if (a.includes("--check")) { if (!existsSync(p) || rd(p) !== content) { console.log("DRIFT " + rel); bad++; } }
      else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, content); } }
    console.log(`${a.includes("--check") ? "checked" : "wrote"} ${files.size} files; lock key ${LOCK_KEY}${bad ? "; " + bad + " drifted" : ""}`); process.exit(bad ? 1 : 0); }
}
